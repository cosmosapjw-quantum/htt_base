"""Memory-bounded real harmonic masked OLS response for finite shells.

Scientific scope: an ordinary least-squares *mask geometry* diagnostic.
NO Planck raw data, Bianchi transfer, covariant EGS epsilon, beam or noise
are generated by this module. The calling site must supply real pixel
center directions, a same-source selection mask, and source provenance.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Iterator

import numpy as np
from scipy.linalg import qr, solve_triangular
from scipy.special import sph_harm_y


@dataclass
class FitGeometry:
    selected_directions: np.ndarray
    q: np.ndarray
    r: np.ndarray
    condition: float
    identity_residual: float


def unit_directions(directions: np.ndarray) -> np.ndarray:
    a = np.asarray(directions, dtype=np.float64)
    if a.ndim != 2 or a.shape[1] != 3 or not np.isfinite(a).all():
        raise ValueError('finite directions shape (n_pixels,3) required')
    if not np.allclose(np.sum(a*a,axis=1),1.0,rtol=0,atol=5e-12):
        raise ValueError('unit directions required')
    return a


def real_harmonic_shell(unit_rows: np.ndarray, ell: int) -> np.ndarray:
    """Original HTT convention: [Y_l0, sqrt(2) Re(Y_lm), sqrt(2) Im(Y_lm)].

    scipy spherical functions use Condon-Shortley phase and (theta,phi)
    where theta is the colatitude; columns are in order m=0,1c,1s,... .
    """
    n=unit_directions(unit_rows)
    if not isinstance(ell,(int,np.integer)) or not (0<=ell<=128):
        raise ValueError('supported integer ell 0..128')
    theta=np.arccos(np.clip(n[:,2],-1.,1.))
    phi=np.arctan2(n[:,1],n[:,0])
    cols=[np.asarray(sph_harm_y(ell,0,theta,phi).real,dtype=np.float64)]
    for m in range(1,ell+1):
        y=sph_harm_y(ell,m,theta,phi)
        cols.append(np.sqrt(2.)*y.real)
        cols.append(np.sqrt(2.)*y.imag)
    result=np.column_stack(cols)
    if not np.isfinite(result).all():
        raise ValueError('real harmonic overflow/NaN')
    return result


def prepare_low_fit(directions: np.ndarray, selected: np.ndarray,
                    *, low_lmax: int=5, cond_limit: float=1e6) -> FitGeometry:
    all_dirs=unit_directions(directions)
    s=np.asarray(selected)
    if s.ndim!=1 or s.shape!=(len(all_dirs),) or s.dtype.kind!='b':
        raise ValueError('explicit boolean selected-pixel mask required')
    nfit=(low_lmax+1)**2
    if low_lmax!=5 or s.sum()<=nfit or not np.isfinite(cond_limit) or cond_limit<=1:
        raise ValueError('full ell0..5 and full-rank support required')
    n=all_dirs[s]
    low=np.column_stack([real_harmonic_shell(n,ell) for ell in range(low_lmax+1)])
    q,r=qr(low,mode='economic',check_finite=False)
    singular=np.linalg.svd(r,compute_uv=False)
    cond=float(singular[0]/singular[-1]) if singular[-1]>0 else float('inf')
    if not np.isfinite(cond) or cond>cond_limit:
        raise ValueError('selected low harmonic fit rank/condition gate failed')
    eye=solve_triangular(r,q.T@low,check_finite=False)
    error=float(np.max(abs(eye-np.eye(nfit))))
    if error>1e-10:
        raise ValueError('low OLS identity failed')
    return FitGeometry(n,q,r,cond,error)


def response_shells(fit: FitGeometry, lo: int=17, hi: int=32) -> tuple[np.ndarray,list[dict]]:
    """Stream one ell shell at a time, avoiding Npixel x Nhigh array."""
    if not (isinstance(lo,int) and isinstance(hi,int) and 6<=lo<=hi<=64):
        raise ValueError('only finite omitted shell range above ell5 is supported')
    pieces=[]
    report=[]
    for ell in range(lo,hi+1):
        h=real_harmonic_shell(fit.selected_directions,ell)
        # The source's exact unweighted normal-equation QR map.
        k=solve_triangular(fit.r,fit.q.T@h,check_finite=False)
        if k.shape!=(36,2*ell+1) or not np.isfinite(k).all():
            raise ValueError('nonfinite finite-shell response')
        pieces.append(k)
        report.append({'ell':ell,'columns':int(2*ell+1),
                       'operator_norm':float(np.linalg.norm(k,ord=2)),
                       'frobenius_norm':float(np.linalg.norm(k))})
    k=np.concatenate(pieces,axis=1)
    if k.shape!=(36,(hi+1)**2-lo**2):
        raise ValueError('harmonic shell count changed')
    return k,report


def inject_omitted_shell(fit:FitGeometry, k:np.ndarray, lo:int, hi:int,
                         *,seed:int=20261016) -> dict:
    """Reconstruction must agree with OLS on selected synthetic pixel sky."""
    if k.shape!=(36,(hi+1)**2-lo**2):
        raise ValueError('source shell shape mismatch')
    high=np.column_stack([real_harmonic_shell(fit.selected_directions,l) for l in range(lo,hi+1)])
    low=np.column_stack([real_harmonic_shell(fit.selected_directions,l) for l in range(6)])
    rng=np.random.default_rng(seed)
    a0=rng.normal(size=36)
    a1=rng.normal(size=k.shape[1])
    sky=low@a0+high@a1
    estimated=solve_triangular(fit.r,fit.q.T@sky,check_finite=False)
    predicted=a0+k@a1
    err=float(np.max(np.abs(estimated-predicted)))
    direct=np.linalg.lstsq(low,sky,rcond=None)[0]
    err_direct=float(np.max(np.abs(estimated-direct)))
    observed_leak=float(np.linalg.norm(estimated-a0))
    upper=float(np.linalg.norm(k,2)*np.linalg.norm(a1))
    if err>1e-9 or err_direct>1e-9 or observed_leak>upper*(1+1e-12):
        raise AssertionError('streamed masked OLS injection failed')
    return {'random_seed':seed,'low_ols_prediction_max_abs':err,
            'independent_lstsq_max_abs':err_direct,
            'injected_high_coeff_norm':float(np.linalg.norm(a1)),
            'observed_finite_leak_norm':observed_leak,
            'operator_upper':upper,
            'bound_holds':True,
            'statistical_unit':'DETERMINISTIC_MANUFACTURED_INJECTION_NOT_A_PLANCK_SKY'}


def streaming_injection(fit:FitGeometry, k:np.ndarray, lo:int=17, hi:int=32,
                        *,seed:int=20261016) -> dict:
    """Check a high-mode sky by accumulating ONE ell shell at a time.

    Never materializes N_selected x 800 on real Planck pixel support;
    worst intermediate is N_selected x 65 when hi=32.
    """
    if k.shape!=(36,(hi+1)**2-lo**2):
        raise ValueError('shell matrix and range mismatch')
    rng=np.random.default_rng(seed)
    low_coeff=rng.normal(size=36)
    high_coeff=rng.normal(size=k.shape[1])
    low=np.column_stack([real_harmonic_shell(fit.selected_directions,l) for l in range(6)])
    sky=low@low_coeff
    start=0
    for ell in range(lo,hi+1):
        ncol=2*ell+1
        sky += real_harmonic_shell(fit.selected_directions,ell)@high_coeff[start:start+ncol]
        start+=ncol
    calculated=solve_triangular(fit.r,fit.q.T@sky,check_finite=False)
    expected=low_coeff+k@high_coeff
    max_residual=float(np.max(abs(calculated-expected)))
    leakage=float(np.linalg.norm(calculated-low_coeff))
    bound=float(np.linalg.norm(k,ord=2)*np.linalg.norm(high_coeff))
    if max_residual>1e-9 or leakage>bound*(1+1e-12):
        raise AssertionError('bounded-memory injection mismatch')
    return {'max_abs_reconstruction_residual':max_residual,
            'coefficient_norm':float(np.linalg.norm(high_coeff)),
            'leakage_norm':leakage,'operator_bound':bound,
            'passed':True,'seed':seed,
            'source_kind':'DECLARED_MANUFACTURED_HIGH_MODE_INJECTION'}


def combined_bounds(k_old:np.ndarray,k_new:np.ndarray,*,retain:slice=slice(4,36))->dict:
    if k_old.shape!=(36,253) or k_new.shape!=(36,800):
        raise ValueError('source/operator matrix dimensions must match')
    a=np.asarray(k_old[retain],float);b=np.asarray(k_new[retain],float)
    old=float(np.linalg.norm(a,2));new=float(np.linalg.norm(b,2))
    combined=float(np.linalg.norm(np.concatenate((a,b),axis=1),2))
    lower=max(old,new)
    upper=float(np.hypot(old,new))
    if combined<lower-1e-9 or combined>upper+1e-9:
        raise AssertionError('positive-semidefinite horizontal Gram bounds violated')
    return {'old_ell6_16_norm':old,'new_ell17_32_norm':new,
            'combined_ell6_32_norm':combined,'psd_lower':lower,'psd_upper':upper,
            'source_semantics':'same low design and selected sky mask; finite real spherical harmonics'}


__all__=['unit_directions','real_harmonic_shell','prepare_low_fit',
         'response_shells','inject_omitted_shell','streaming_injection','combined_bounds','FitGeometry']
