"""R54-L06: joint frame tomography L(theta | a_lm, z, n, counts) in precision form, one carrier per irreducible block.

Steps follow LOCAL_AGENT_CONTRACT.json:nodes[R54-L06]; deviations are in DEVIATIONS.json (DV-L06-*):
 1. typed carriers per block: polar vector (V_w per depth, A_cal, beta_ex), STF2 (s0, q_cal), axial vector (omega: no column)
 2. probes added as (F, t); singular blocks are reported, never regularised
 3. transport hypotheses on the same data and covariance; tilt closure (R54-EQ-38) with the R54-L03 count covariance
 4. five views per block; identification table with the stated scale vector
 5. RESULTS/R54_L06_JOINT.json (the manuscript table is generated by the builder)
Claim tier C0.
"""
