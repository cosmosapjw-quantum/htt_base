REPO_ROOT = Path(__file__).resolve().parents[1]
COMMON_ROOT = REPO_ROOT / "htt" / "src"
if str(COMMON_ROOT) not in sys.path:
    sys.path.insert(0, str(COMMON_ROOT))

from common.contracts import ArtifactManifest, ClaimLedgerEntry, StatusSnapshotEntry


STATUS_JSON = REPO_ROOT / "docs" / "ver2_upgrade" / "generated" / "status_snapshot.json"
CLAIM_JSON = REPO_ROOT / "docs" / "ver2_upgrade" / "generated" / "claim_ledger.json"
VER2_GEN = REPO_ROOT / "docs" / "ver2_upgrade" / "generated"
