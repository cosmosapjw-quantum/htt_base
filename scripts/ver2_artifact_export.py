FIGURE_ROOT = REPO_ROOT / "figures" / "paper"


def _field_names(contract: type[object]) -> list[str]:
    return [field.name for field in fields(contract)]


def _load_rows(path: Path, required_fields: list[str]) -> list[dict[str, object]] | None:
    if not path.exists():
        return None
    payload = json.loads(path.read_text())
    if not isinstance(payload, list):
        raise ValueError(f"{path} must contain a JSON list")
    rows: list[dict[str, object]] = []
    for index, row in enumerate(payload):
        if not isinstance(row, dict):
            raise ValueError(f"{path} row {index} is not a JSON object")
        missing = [name for name in required_fields if name not in row]
        if missing:
            raise ValueError(f"{path} row {index} missing required fields: {missing}")
        rows.append(row)
    return rows


def _escape_tex(text: object) -> str:
    value = str(text)
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    for old, new in replacements.items():
        value = value.replace(old, new)
    return value


def _scan_figures(root: Path) -> list[dict[str, object]]:
    figures: dict[tuple[str, str], dict[str, object]] = {}
    for asset in sorted(root.rglob("*")):
        if not asset.is_file():
            continue
        suffixes = asset.suffixes
        if suffixes[-1:] in ([".png"], [".pdf"]):
            stem = asset.stem
        elif suffixes[-2:] == [".caption", ".txt"]:
            stem = asset.name[:-len(".caption.txt")]
        elif suffixes[-2:] == [".manifest", ".json"]:
            stem = asset.name[:-len(".manifest.json")]
        else:
            continue
        chapter = asset.parent.relative_to(root).as_posix()
        key = (chapter, stem)
        entry = figures.setdefault(
            key,
            {
                "chapter": chapter,
                "stem": stem,
                "has_png": False,
                "has_pdf": False,
                "has_caption": False,
                "has_manifest": False,
            },
        )
        if suffixes[-1:] == [".png"]:
            entry["has_png"] = True
        elif suffixes[-1:] == [".pdf"]:
            entry["has_pdf"] = True
        elif suffixes[-2:] == [".caption", ".txt"]:
            entry["has_caption"] = True
        elif suffixes[-2:] == [".manifest", ".json"]:
            entry["has_manifest"] = True
    ordered = sorted(figures.values(), key=lambda row: (row["chapter"], row["stem"]))
    for row in ordered:
        assets = []
        if row["has_png"]:
            assets.append("png")
        if row["has_pdf"]:
            assets.append("pdf")
        if row["has_caption"]:
            assets.append("caption")
        row["assets"] = ", ".join(assets) or "none"
        row["export_status"] = (
            "manifest_ready" if row["has_manifest"] else "blocked_no_manifest"
        )
    return ordered


def _render_status_markdown(
    rows: list[dict[str, object]] | None,
    status_fields: list[str],
) -> str:
    header = dedent(
        """\
        <!-- Generated by scripts/ver2_artifact_export.py -->
        # VER2 Status Snapshot

        Semantic source: `htt/src/common/contracts.py::StatusSnapshotEntry`
        """
    )
    if rows is None:
        field_line = ", ".join(f"`{name}`" for name in status_fields)
        return header + dedent(
            f"""\

            No `status_snapshot.json` is published yet.

            Until `IM-08V` emits `docs/ver2_upgrade/generated/status_snapshot.json`,
            manuscript-facing status counts remain intentionally omitted. The shared
            snapshot contract is already frozen; required fields are: {field_line}.
            """
        )

    by_owner = Counter(str(row["owner"]) for row in rows)
    total = len(rows)
    implemented = sum(bool(row["implemented"]) for row in rows)
    smoke_tested = sum(bool(row["smoke_tested"]) for row in rows)
    production_validated = sum(bool(row["production_validated"]) for row in rows)
    manuscript_used = sum(bool(row["manuscript_used"]) for row in rows)
    table = "\n".join(
        f"| `{owner}` | {count} |" for owner, count in sorted(by_owner.items())
    )
    return header + dedent(
        f"""\

        | Metric | Count |
        | --- | ---: |
        | Total rows | {total} |
        | Implemented | {implemented} |
        | Smoke tested | {smoke_tested} |
        | Production validated | {production_validated} |
        | Manuscript used | {manuscript_used} |

        | Owner | Rows |
        | --- | ---: |
        {table}
        """
    )


