#!/usr/bin/env python3
"""VER2 artifact/manuscript skeleton exporter.

This script is the SK-09D solver-independent export surface. It does not
promote figures or manuscript claims. Instead it renders placeholder
manuscript snippets, Markdown mirrors, and a figure-manifest audit that all
bind to the canonical shared contracts under ``htt/src/common``.

Usage:
    venv/bin/python scripts/ver2_artifact_export.py
    venv/bin/python scripts/ver2_artifact_export.py --check
"""
