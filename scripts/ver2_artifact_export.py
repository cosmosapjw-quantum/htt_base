def _render_manifest_index(
    figures: list[dict[str, object]],
    manifest_fields: list[str],
) -> str:
    missing = sum(not bool(row["has_manifest"]) for row in figures)
    rows = "\n".join(
        (
            f"| `{row['chapter']}` | `{row['stem']}` | {row['assets']} | "
            f"{'yes' if row['has_manifest'] else 'no'} | `{row['export_status']}` |"
        )
        for row in figures
    )
    field_line = ", ".join(f"`{name}`" for name in manifest_fields)
    return dedent(
        f"""
<!-- Generated by scripts/ver2_artifact_export.py -->
# VER2 Figure Manifest Index

This is the SK-09D manifest audit surface for the legacy paper figure tree.
It does not promote any figure. It records which figure bases already have
the minimum file trio (`png`, `pdf`, `caption`) and whether the canonical
`ArtifactManifest` sidecar exists.

Current state:
- Figure bases scanned: {len(figures)}
- Missing manifests: {missing}
- Export rule: no figure or table may be promoted into the VER2 manuscript
  path unless a matching `.manifest.json` exists.
- Canonical manifest fields remain owned by `common.contracts`:
  {field_line}

| Chapter | Figure base | Assets | Manifest | Export status |
| --- | --- | --- | --- | --- |
{rows}
"""
    ).strip() + "\n"


def _render_all(
    status_rows: list[dict[str, object]] | None,
    claim_rows: list[dict[str, object]] | None,
    figures: list[dict[str, object]],
) -> dict[Path, str]:
    status_fields = _field_names(StatusSnapshotEntry)
    claim_fields = _field_names(ClaimLedgerEntry)
    manifest_fields = _field_names(ArtifactManifest)
    return {
        VER2_GEN / "STATUS_SNAPSHOT.md": _render_status_markdown(status_rows, status_fields),
        VER2_GEN / "CLAIM_LEDGER.md": _render_claim_markdown(claim_rows, claim_fields),
        VER2_GEN / "RESULT_PACK_INDEX.md": _render_result_pack_index(),
        MANUSCRIPT_GEN / "ver2_titlepage_status.tex": _render_titlepage_status_tex(status_rows),
        MANUSCRIPT_GEN / "ver2_status_snapshot.tex": _render_status_snapshot_tex(status_rows),
        MANUSCRIPT_GEN / "ver2_claim_ledger.tex": _render_claim_ledger_tex(claim_rows),
        MANUSCRIPT_GEN / "ver2_artifact_export_policy.tex": _render_artifact_policy_tex(
            manifest_fields,
            figures,
        ),
        MANUSCRIPT_GEN / "ver2_tsc_scope_boundary.tex": _render_tsc_scope_boundary_tex(),
        MANUSCRIPT_GEN / "ver2_source_vs_propagation.tex": _render_source_vs_propagation_tex(),
        MANUSCRIPT_GEN / "ver2_channel_responsibility.tex": _render_channel_responsibility_tex(),
        FIGURE_ROOT / "VER2_MANIFEST_INDEX.md": _render_manifest_index(
            figures,
            manifest_fields,
        ),
    }


def _write_outputs(outputs: dict[Path, str]) -> None:
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content.rstrip() + "\n")


def _check_outputs(outputs: dict[Path, str]) -> int:
    stale: list[str] = []
    for path, content in outputs.items():
        expected = content.rstrip() + "\n"
        actual = path.read_text() if path.exists() else None
        if actual != expected:
            stale.append(path.relative_to(REPO_ROOT).as_posix())
    if stale:
        print("Out-of-date VER2 export surfaces:")
        for path in stale:
            print(f"  - {path}")
        return 1
    print("VER2 export surfaces are up to date.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if generated export surfaces are missing or stale",
    )
    args = parser.parse_args()

    status_rows = _load_rows(STATUS_JSON, _field_names(StatusSnapshotEntry))
    claim_rows = _load_rows(CLAIM_JSON, _field_names(ClaimLedgerEntry))
    figures = _scan_figures(FIGURE_ROOT)
    outputs = _render_all(status_rows, claim_rows, figures)

    if args.check:
        return _check_outputs(outputs)

    _write_outputs(outputs)
    missing = sum(not bool(row["has_manifest"]) for row in figures)
    print(
        "Generated VER2 export skeleton surfaces "
        f"({len(outputs)} files; {len(figures)} figure bases scanned; "
        f"{missing} missing manifests)."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
