# ----------------------------------------------------------------- structural against numeric identification (T6, T7a)
def test_structural_and_numeric_identification_layers_agree():
    """Structural layer (block_identification) and numeric layer (fv.identify) for the zero-point gauge of T7a."""
    rng = np.random.default_rng(20261116)
    multiplicity = {(1, "-"): np.array([[1.0, 1.0, 0.0], [1.0, 0.0, 1.0]]),                   # slots: dipole of sample 1, 2; copies: delta, d_1, d_2
                    (1, "+"): np.zeros((0, 1)),                                               # vorticity: no scalar slot (T6, C6.1)
                    (2, "+"): np.array([[1.0], [1.0]])}                                       # shear seen by two quadrupole slots
    table = idn.block_identification(multiplicity)
    assert table["blocks"]["1-"] == {"slots": 2, "copies": 3, "rank": 2, "nullity": 1, "unidentified_dimension": 3}
    assert table["blocks"]["1+"] == {"slots": 0, "copies": 1, "rank": 0, "nullity": 1, "unidentified_dimension": 3}
    assert table["blocks"]["2+"]["unidentified_dimension"] == 0 and table["unidentified_dimension"] == 6 and table["identified"] is False

    def precision(directions):                                                                # numeric layer of the polar block: rows n.(delta + d_p)
        rows = []
        for p, nhat in enumerate(directions):
            block = np.zeros((len(nhat), 9))
            block[:, 0:3], block[:, 3 * (p + 1):3 * (p + 2)] = nhat, nhat
            rows.append(block)
        design = np.vstack(rows)
        return design.T @ design

    full = [v / np.linalg.norm(v, axis=1, keepdims=True) for v in (rng.normal(size=(40, 3)), rng.normal(size=(50, 3)))]
    numeric = fv.identify(precision(full)).null_basis.shape[1]
    assert numeric == table["blocks"]["1-"]["unidentified_dimension"]                          # full sky sampling: equality
    planar = [np.column_stack([v[:, 0], v[:, 1], np.zeros(len(v))]) for v in full]            # degenerate sampling adds null directions, never removes one
    assert fv.identify(precision(planar)).null_basis.shape[1] > numeric
    with pytest.raises(ValueError):
        idn.block_identification({(1, "x"): np.ones((1, 1))})
