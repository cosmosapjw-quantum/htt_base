"""Merge helper of the R54 handoff update and one executable link between the theorems and the five-view module.

scripts/r54/handoff_merge.py delivers the update to a branch that already carries local-node work. It is exercised
here on scratch repositories: a conflicted generated document is resolved by taking one side (it is rebuilt afterwards),
a conflicted hand-written file is left to the agent, and an unsafe state blocks before anything is changed (gate MG-35).
No test in this file reads a generated document, so the file can belong to the unmutated suite of the mutation receipt.
"""
from __future__ import annotations

import importlib.util
import subprocess
import sys
from pathlib import Path

import numpy as np
import pytest

from htt.htt.infer import r54_identifiability as idn
from htt.htt.infer import r54_tensor_five_view as fv

ROOT = Path(__file__).resolve().parents[2]
GIT = ["git", "-c", "user.name=r54-test", "-c", "user.email=r54-test@example.invalid", "-c", "commit.gpgsign=false", "-c", "core.hooksPath=/dev/null"]
BUILDER = "scripts/r54/build_r54_contract.py"


def _load(rel: str, name: str):
    path = ROOT / rel
    for extra in (ROOT / "htt", ROOT / "htt/src", ROOT, path.parent):
        if str(extra) not in sys.path:
            sys.path.insert(0, str(extra))
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


@pytest.fixture(scope="module")
def hm():
    return _load("scripts/r54/handoff_merge.py", "r54_handoff_merge")


def _git(repo: Path, *args: str) -> str:
    res = subprocess.run([*GIT, *args], cwd=repo, capture_output=True, text=True)
    assert res.returncode == 0, f"git {' '.join(args)}: {res.stderr}"
    return res.stdout.strip()


def _write(repo: Path, rel: str, text: str) -> None:
    path = repo / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def _scratch(base: Path, hm, local_work: bool = True, update_touches: str | None = None) -> tuple[Path, str]:
    """Scratch repository: a start commit, an update fetched as the helper's source ref, and optionally conflicting local work."""
    repo = base / "repo"
    repo.mkdir(parents=True)
    _git(repo, "init", "-q")
    _git(repo, "symbolic-ref", "HEAD", "refs/heads/work")
    doc, result = f"{hm.REL}/README.md", f"{hm.REL}/RESULTS/R.json"
    for rel, text in ((doc, "generated at the start\n"), (BUILDER, "builder at the start\n"), (result, "{}\n"), ("docs/codex_handoff/pr_status.yaml", "a: 1\n")):
        _write(repo, rel, text)
    _git(repo, "add", "-A")
    _git(repo, "commit", "-q", "-m", "start")
    start = _git(repo, "rev-parse", "HEAD")
    _git(repo, "checkout", "-q", "-b", "update")
    _write(repo, doc, "generated by the update\n")
    _write(repo, BUILDER, "builder of the update\n")
    _write(repo, f"{hm.REL}/THEOREMS.md", "statements\n")
    if update_touches:
        _write(repo, update_touches, '{"changed": true}\n')
    _git(repo, "add", "-A")
    _git(repo, "commit", "-q", "-m", "update")
    _git(repo, "update-ref", hm.SOURCE_REF, "HEAD")
    _git(repo, "checkout", "-q", "work")
    if local_work:
        _write(repo, doc, "generated by the local session\n")
        _write(repo, BUILDER, "builder of the local session\n")
        _git(repo, "add", "-A")
        _git(repo, "commit", "-q", "-m", "local work")
    return repo, start


# ----------------------------------------------------------------- merge helper
def test_merge_helper_never_resolves_a_hand_written_file(hm, tmp_path):                       # MG-35
    repo, start = _scratch(tmp_path, hm)
    doc = f"{hm.REL}/README.md"
    assert hm.preflight(repo, start)[0] == "MERGE"
    assert hm.apply(repo, start) == "MERGE_CONFLICTS"
    assert hm.unmerged(repo) == [BUILDER]                                                     # the hand-written file is left to the agent
    text = (repo / BUILDER).read_text(encoding="utf-8")
    assert "<<<<<<<" in text and "builder of the local session" in text and "builder of the update" in text   # nothing was discarded
    assert (repo / doc).read_text(encoding="utf-8") == "generated by the update\n"            # one side taken; `finish` rebuilds it
    assert (repo / f"{hm.REL}/THEOREMS.md").is_file()
    assert any(b.startswith("unmerged") for b in hm.finish_blockers(repo))
    _git(repo, "add", BUILDER)                                                                # staged with its markers: still blocked
    assert any("conflict marker" in b for b in hm.finish_blockers(repo))
    _write(repo, BUILDER, "builder of the local session\nbuilder of the update\n")
    _git(repo, "add", BUILDER)
    assert hm.finish_blockers(repo) == [] and hm.preflight(repo, start)[0] == "MERGE_IN_PROGRESS"
    assert _git(repo, "log", "-1", "--format=%s") == "local work"                             # the helper never commits
    for rel in (BUILDER, "tests/r54/test_r54_results_binding.py", "tests/r54/test_r54_handoff.py", "htt/htt/htt/infer/r54_lcdm_body.py", f"{hm.REL}/THEOREMS.md",
                f"{hm.REL}/INDEPENDENT_REVIEW.json", f"{hm.REL}/RESULTS/R54_L05_CF4_EXACT.json", "docs/codex_handoff/pr_status.yaml", "AGENTS.md"):
        assert hm.classify(rel) == "hand_written", rel
        assert hm.rule_for(rel) and "rebuilt" not in hm.rule_for(rel)


def test_merge_helper_fast_forwards_a_branch_without_local_commits(hm, tmp_path):
    repo, start = _scratch(tmp_path, hm, local_work=False)
    assert hm.preflight(repo, start)[0] == "FAST_FORWARD"
    assert hm.apply(repo, start) == "FAST_FORWARDED"
    assert _git(repo, "rev-parse", "HEAD") == _git(repo, "rev-parse", hm.SOURCE_REF) and hm.finish_blockers(repo) == []
    assert hm.apply(repo, start) == "ALREADY_APPLIED"


def test_merge_helper_blocks_before_it_changes_anything(hm, tmp_path):
    repo, start = _scratch(tmp_path / "dirty", hm)
    head = _git(repo, "rev-parse", "HEAD")
    _write(repo, BUILDER, "uncommitted edit\n")
    assert hm.apply(repo, start) == "BLOCKED" and not hm.merging(repo)                         # uncommitted work
    _git(repo, "checkout", "-q", "--", BUILDER)
    backup = "scripts/r54/handoff_merge.py" + hm.BACKUP_SUFFIX
    _write(repo, backup, "safety copy\n")
    assert hm.preflight(repo, start)[0] == "BLOCKED" and any("interrupted" in b for b in hm.finish_blockers(repo))   # a killed mutation receipt
    (repo / backup).unlink()
    assert hm.preflight(repo, "0" * 40)[0] == "BLOCKED"                                        # a branch that does not contain the start commit
    _git(repo, "checkout", "-q", "-b", "main")
    assert hm.apply(repo, start) == "BLOCKED"                                                  # never merged into a protected branch
    _git(repo, "checkout", "-q", "work")
    assert _git(repo, "rev-parse", "HEAD") == head and not hm.merging(repo)
    for i, path in enumerate((f"{hm.REL}/RESULTS/R.json", "scripts/r54/run_r54_cf4_exact.py", "tests/r54/test_r54_modules.py")):
        other, begin = _scratch(tmp_path / f"touch{i}", hm, update_touches=path)
        assert hm.apply(other, begin) == "BLOCKED" and not hm.merging(other), path             # an update that changes what it declares untouched
    bare = tmp_path / "unfetched"
    bare.mkdir()
    _git(bare, "init", "-q")
    assert hm.preflight(bare, start)[0] == "BLOCKED"                                           # the update was not fetched


def test_merge_helper_blocks_an_open_merge_of_another_commit(hm, tmp_path):
    """Review finding R54-A1-03: an open merge that is not the update is never resolved, on any branch."""
    repo, start = _scratch(tmp_path, hm)
    doc = f"{hm.REL}/README.md"
    _git(repo, "checkout", "-q", "-b", "other", start)
    _write(repo, doc, "generated by an unrelated branch\n")
    _git(repo, "add", "-A")
    _git(repo, "commit", "-q", "-m", "unrelated")
    _git(repo, "checkout", "-q", "work")
    subprocess.run([*GIT, "merge", "--no-ff", "--no-commit", "other"], cwd=repo, capture_output=True, text=True)
    assert hm.merging(repo) and hm.unmerged(repo) == [doc]
    assert hm.preflight(repo, start)[0] == "BLOCKED" and hm.apply(repo, start) == "BLOCKED"
    assert hm.unmerged(repo) == [doc] and "<<<<<<<" in (repo / doc).read_text(encoding="utf-8")   # nothing was taken or staged
    _git(repo, "merge", "--abort")
    _git(repo, "checkout", "-q", "-b", "main")
    subprocess.run([*GIT, "merge", "--no-ff", "--no-commit", hm.SOURCE_REF], cwd=repo, capture_output=True, text=True)
    assert hm.merging(repo) and hm.preflight(repo, start)[0] == "BLOCKED"                     # a protected branch blocks even an open merge of the update


def test_merge_helper_and_builder_agree(hm):
    builder = _load(BUILDER, "r54_builder_for_handoff")
    assert sorted(hm.GENERATED_NAMES) == sorted(builder.GENERATED_NAMES) and len(set(hm.GENERATED_NAMES)) == len(hm.GENERATED_NAMES)
    assert (hm.REL, hm.SOURCE_BRANCH, hm.START_COMMIT, hm.BACKUP_SUFFIX) == (builder.REL, builder.SOURCE_BRANCH, builder.START_COMMIT, builder.BACKUP_SUFFIX)
    assert hm.FETCH == builder.HANDOFF_FETCH and sorted(hm.UNTOUCHED) == sorted(builder.HANDOFF_UNTOUCHED) and hm.RESERVED == builder.RESERVED_TEXT
    assert all(hm.classify(p) == "generated" for p in hm.GENERATED) and hm.classify(hm.RECEIPT) == "receipt" and all(hm.classify(m) == "mirror" for m in hm.MIRRORS)
    source = (ROOT / "scripts/r54/handoff_merge.py").read_text(encoding="utf-8")
    for name in builder.HANDOFF_RESULTS:                                                       # every result line of the handoff text is one the helper can print
        assert f'"{name}"' in source, name
    assert "HANDOFF OK" in source and "HANDOFF FAILED" in source and builder.HANDOFF_COMMIT in source
    gate_dirs = {str(Path(g[1]).parent) for g in builder.implemented_gates()}
    assert gate_dirs <= set(hm.BACKUP_DIRS)                                                    # every place where the receipt mutates a file is searched for safety copies


