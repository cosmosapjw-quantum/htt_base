/// Interpolate xe at redshift z from CAMB table.
pub(crate) fn camb_xe(z: f64) -> f64 {
    if z <= CAMB_XE_Z[0] { return CAMB_XE_VAL[0]; }
    let n = CAMB_XE_Z.len();
    if z >= CAMB_XE_Z[n-1] { return CAMB_XE_VAL[n-1]; }
    let mut lo = 0usize; let mut hi = n - 1;
    while hi - lo > 1 { let m = (lo+hi)/2; if CAMB_XE_Z[m] <= z { lo = m; } else { hi = m; } }
    let w = (z - CAMB_XE_Z[lo]) / (CAMB_XE_Z[hi] - CAMB_XE_Z[lo]);
    CAMB_XE_VAL[lo] + w * (CAMB_XE_VAL[hi] - CAMB_XE_VAL[lo])
}
