/// Interpolate CAMB visibility quantities at redshift z.
/// Returns (opacity κ', visibility g, dg/dτ, d²g/dτ²)
pub(crate) fn camb_vis_at_z(z: f64) -> (f64, f64, f64, f64) {
    let n = CAMB_VIS_N;
    if z <= CAMB_VIS_Z[0] { return (CAMB_VIS_OPAC[0], CAMB_VIS_VIS[0], CAMB_VIS_DVIS[0], CAMB_VIS_DDVIS[0]); }
    if z >= CAMB_VIS_Z[n-1] { return (CAMB_VIS_OPAC[n-1], CAMB_VIS_VIS[n-1], CAMB_VIS_DVIS[n-1], CAMB_VIS_DDVIS[n-1]); }
    let mut lo = 0usize; let mut hi = n - 1;
    while hi - lo > 1 { let m = (lo+hi)/2; if CAMB_VIS_Z[m] <= z { lo = m; } else { hi = m; } }
    let w = (z - CAMB_VIS_Z[lo]) / (CAMB_VIS_Z[hi] - CAMB_VIS_Z[lo]);
    (
        CAMB_VIS_OPAC[lo] + w * (CAMB_VIS_OPAC[hi] - CAMB_VIS_OPAC[lo]),
        CAMB_VIS_VIS[lo]  + w * (CAMB_VIS_VIS[hi]  - CAMB_VIS_VIS[lo]),
        CAMB_VIS_DVIS[lo] + w * (CAMB_VIS_DVIS[hi] - CAMB_VIS_DVIS[lo]),
        CAMB_VIS_DDVIS[lo]+ w * (CAMB_VIS_DDVIS[hi]- CAMB_VIS_DDVIS[lo]),
    )
}
